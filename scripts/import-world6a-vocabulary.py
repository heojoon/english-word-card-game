"""Import WordMax Level 3 Day 1–10 for World 6A (two stages per full Day).

Usage: python3 scripts/import-world6a-vocabulary.py '/path/to/교사용 CD Level 3.xlsx'
Read-only XLSX extraction using the standard library; never evaluate cell formulas.
"""
import hashlib
import json
import posixpath
import re
import sys
import unicodedata
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

NS = {'s': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
REL = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'


def clean(value):
    return re.sub(r'\s+', ' ', re.sub(r'\s*\n\s*', ', ', value)).strip()


def import_days(path):
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    days = []
    with zipfile.ZipFile(path) as archive:
        shared = []
        if 'xl/sharedStrings.xml' in archive.namelist():
            shared = [''.join(si.itertext()) for si in ET.fromstring(archive.read('xl/sharedStrings.xml'))]
        relations = {item.attrib['Id']: item.attrib['Target'] for item in ET.fromstring(archive.read('xl/_rels/workbook.xml.rels'))}
        sheets = {item.attrib['name']: relations[item.attrib[f'{{{REL}}}id']] for item in ET.fromstring(archive.read('xl/workbook.xml')).find('s:sheets', NS)}
        for day in range(1, 11):
            name = f'Day {day}'
            target = sheets[name]
            sheet_path = target.lstrip('/') if target.startswith('/') else posixpath.normpath('xl/' + target)
            words, rows = [], []
            for row in ET.fromstring(archive.read(sheet_path)).find('s:sheetData', NS):
                row_number = int(row.attrib['r'])
                if not 5 <= row_number <= 34:
                    continue
                cells = {}
                for cell in row:
                    value = cell.find('s:v', NS)
                    text = value.text if value is not None else ''
                    if cell.attrib.get('t') == 's':
                        text = shared[int(text)]
                    elif cell.attrib.get('t') == 'inlineStr':
                        text = ''.join(cell.find('s:is', NS).itertext())
                    cells[re.sub(r'\d', '', cell.attrib['r'])] = clean(text or '')
                english, meaning = cells.get('B', ''), cells.get('D', '')
                if not english or not meaning or not re.search('[A-Za-z]', english):
                    raise ValueError(f'Missing vocabulary: {name} row {row_number}')
                words.append([english, '—', meaning])
                rows.append(row_number)
            if len(words) != 30 or len({word[0].casefold() for word in words}) != 30:
                raise ValueError(f'Expected 30 unique English entries: {name}')
            if len({word[2] for word in words}) != 30:
                raise ValueError(f'Ambiguous duplicate meanings: {name}')
            days.append({'day': day, 'source': {'workbook': unicodedata.normalize('NFC', path.name), 'sha256': digest, 'sheet': name, 'englishRange': f'B{rows[0]}:B{rows[-1]}', 'meaningRange': f'D{rows[0]}:D{rows[-1]}', 'partOfSpeech': 'not supplied', 'corrections': []}, 'words': words})
    return days


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    days = import_days(Path(sys.argv[1]))
    stages = {}
    for day in days:
        for prefix, level in [('s', 'middle'), ('e', 'elementary')]:
            stages[f"{prefix}{day['day'] + 34}"] = {'name': f"월드 6A · Day {day['day']}", 'desc': f"WordMax Level 3 · Day {day['day']} · 30단어", 'learningLevel': level, 'storyChapter': 7, 'questionCount': 30, 'source': day['source'], 'words': day['words']}
    (root / 'stage35.js').write_text('// Generated by scripts/import-world6a-vocabulary.py. World 6A only.\nwindow.QUIZ_STAGES = window.QUIZ_STAGES || {};\nObject.assign(window.QUIZ_STAGES, ' + json.dumps(stages, ensure_ascii=False, indent=2) + ');\n', encoding='utf-8')
    snapshot = root / 'content/sources/wordmax-level3-day1-10.json'
    snapshot.parent.mkdir(parents=True, exist_ok=True)
    snapshot.write_text(json.dumps({'world': '6A', 'mapping': 'Full Day for each consecutive pair of stages: 1–2 = Day 1, …, 19–20 = Day 10', 'days': days}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Generated stage35.js: {len(days)} Days, {sum(len(day["words"]) for day in days)} source entries, both learning levels.')
