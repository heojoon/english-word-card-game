import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'content/world-eleven-vocabulary.json');
const targetPath = path.join(root, 'world-eleven-content.js');
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
const fail = message => { throw new Error(`World Eleven: ${message}`); };
const sourceIds = new Set(source.sources.map(item => item.id));
const output = { sources: source.sources, levels: {} };

for (const level of ['elementary', 'middle']) {
  const data = source.levels[level];
  if (!data || data.stages.length !== 44) fail(`${level} requires 44 stages`);
  const items = new Map();
  const englishPool = new Set();
  for (const item of data.items) {
    if (items.has(item.id)) fail(`duplicate item ID ${item.id}`);
    if (item.level !== level || !item.topic || !item.difficulty) fail(`invalid level/topic/difficulty: ${item.id}`);
    if (![item.en, item.displayLabel, item.ko].every(text => typeof text === 'string' && text.trim() === text && text.length)) fail(`invalid row: ${item.id}`);
    if (item.displayLabel !== (/\s/.test(item.en) ? '표현' : '단어') || item.phonetics !== null) fail(`invalid visible label or phonetics policy: ${item.id}`);
    if (englishPool.has(item.en.toLowerCase())) fail(`duplicate source English: ${level}/${item.en}`);
    if (typeof item.authoredExtension !== 'boolean' || !item.sourceIds?.length || !item.sourceIds.every(id => sourceIds.has(id))) fail(`missing provenance: ${item.id}`);
    if (!item.evidence?.length || !item.evidence.every(entry => sourceIds.has(entry.sourceId) && entry.locator && entry.headwords?.length)) fail(`missing lexical evidence: ${item.id}`);
    for (const evidence of item.evidence) {
      if (evidence.headwordLocations?.length !== evidence.headwords.length || !evidence.headwordLocations.every((entry, index) => entry.headword === evidence.headwords[index] && Number.isInteger(entry.pdfPage) && entry.pdfPage > 0)) fail(`missing PDF evidence location: ${item.id}`);
    }
    englishPool.add(item.en.toLowerCase());
    items.set(item.id, item);
  }
  const assigned = new Set();
  output.levels[level] = data.stages.map((stage, index) => {
    if (stage.number !== index + 1 || !stage.name || stage.itemIds.length !== 30) fail(`invalid stage: ${level}/${index + 1}`);
    const en = new Set(), ko = new Set();
    const words = stage.itemIds.map(id => {
      const item = items.get(id);
      if (!item) fail(`unknown item ${id}`);
      if (en.has(item.en.toLowerCase()) || ko.has(item.ko)) fail(`ambiguous answer: ${level}/${stage.number}/${item.en}`);
      en.add(item.en.toLowerCase());
      ko.add(item.ko);
      assigned.add(id);
      return [item.en, item.displayLabel, item.ko];
    });
    return { number: stage.number, name: stage.name, words };
  });
  if (assigned.size !== items.size) fail(`${level} has unassigned items`);
}
const generated = `// Generated by scripts/generate-world-eleven-content.mjs; edit content/world-eleven-vocabulary.json.\n// Rows are [English, visible classification label, Korean]; phonetics are not provided.\nwindow.WORDORIA_WORLD_ELEVEN_CONTENT = ${JSON.stringify(output, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(targetPath) || fs.readFileSync(targetPath, 'utf8') !== generated) fail('generated runtime is stale; run node scripts/generate-world-eleven-content.mjs');
  console.log('World Eleven runtime content is up to date.');
} else {
  fs.writeFileSync(targetPath, generated);
  console.log('Generated world-eleven-content.js: elementary 44×30; middle 44×30.');
}
