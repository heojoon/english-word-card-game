import {chromium} from 'playwright';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,reducedMotion:'reduce'});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>localStorage.setItem('wordoria-production-demo-v1',JSON.stringify({storyBranch:'6A'})));
await page.goto('http://127.0.0.1:3000/?demo=1',{waitUntil:'networkidle'});
await page.locator('#entry-guest').click();
await page.waitForFunction(()=>document.querySelector('#screen')?.innerText.length>30);
await page.locator('#screen [data-page="dungeon"]').click();
await page.locator('[data-action="mode-select"][data-mode="story"]').click();
for(const next of [2,3,4,5,7,8])await page.locator(`[data-action="story-world-select"][data-world="${next}"]`).click();
const map=page.locator('.story-world-map-8');
await map.locator('img.story-world-map-art').evaluate(im=>im.decode());
const nodes=await map.locator('.story-map-node').count();
if(nodes!==30)throw Error(`Expected 30 nodes, got ${nodes}`);
await map.screenshot({path:'output/story-map/world7a-mobile-map.png'});
await map.locator('.story-map-node-30').scrollIntoViewIfNeeded();
await page.screenshot({path:'output/story-map/world7a-mobile-map-bottom.png'});
const alignment=await map.evaluate(el=>{
  const im=el.querySelector('img').getBoundingClientRect();
  return [...el.querySelectorAll('.story-map-node')].map(b=>{const r=b.getBoundingClientRect();return {stage:b.dataset.stage,x:(r.x+r.width/2-im.x)/im.width*100,y:(r.y+r.height/2-im.y)/im.height*100,width:r.width,height:r.height}});
});
await page.locator('[data-stage="story-ch7a-1"]').click();
await page.locator('[data-stage="story-ch7a-1"]').click();
console.log('confirmation',await page.locator('#dialog-content').innerText());
await page.locator('[data-action="story-enter-confirm"]').click();
await page.waitForSelector('.story-match-board');
const matchButtons=await page.locator('.story-match-item').count();
if(matchButtons!==10)throw Error('Expected five matching pairs');
await page.screenshot({path:'output/story-map/world7a-mobile-battle.png'});
await page.setViewportSize({width:1280,height:900});
await page.reload({waitUntil:'networkidle'});
if(await page.locator('body.entry-active').count())await page.locator('#entry-guest').click();
await page.waitForFunction(()=>document.querySelector('#screen')?.innerText.length>30);
await page.locator('#screen [data-page="dungeon"]').click();
await page.locator('[data-action="mode-select"][data-mode="story"]').click();
for(const next of [2,3,4,5,7,8])await page.locator(`[data-action="story-world-select"][data-world="${next}"]`).click();
await page.locator('.story-world-map-8').screenshot({path:'output/story-map/world7a-desktop-map.png'});
await writeFile('output/story-map/world7a-browser-review.json',JSON.stringify({nodes,matchButtons,alignment,errors},null,2));
console.log(JSON.stringify({nodes,matchButtons,errors}));
await browser.close();
