-- Production verification uses temporary fixtures and rolls back every change.
begin;
do $test$
declare own uuid:=gen_random_uuid(); c uuid; other_c uuid; sid uuid; v_abandoned uuid; receipt record; again record; before_balance integer;
begin
  insert into auth.users(id) values(own);
  insert into public.profiles(user_id,display_name,crystal_balance) values(own,'hidtest',0) on conflict(user_id) do nothing;
  insert into public.game_characters(player,name,class,owner_user_id) values('hidtest','one','warrior',own) returning id into c;
  insert into public.game_characters(player,name,class,owner_user_id) values('hidtest','two','mage',own) returning id into other_c;
  insert into public.world_five_hidden_unlocks(character_id) values(c);
  perform set_config('request.jwt.claim.sub',own::text,true);
  v_abandoned:=public.begin_world_five_hidden(c,'king');
  sid:=public.begin_world_five_hidden(c,'king');
  if not exists(select 1 from public.world_five_hidden_runs where id=v_abandoned and abandoned=true) then raise exception 'refresh did not abandon old session'; end if;
  select * into receipt from public.finish_world_five_hidden(sid,array[]::integer[],700,1000,false);
  if receipt.coins_earned<>0 or receipt.pet_granted then raise exception 'exit rewarded'; end if;
  sid:=public.begin_world_five_hidden(c,'king');
  update public.world_five_hidden_runs set started_at=now()-interval '5 minutes' where id=sid;
  select * into receipt from public.finish_world_five_hidden(sid,array[]::integer[],500,300000,true);
  if receipt.coins_earned<>750 or not receipt.pet_granted then raise exception 'first clear reward missing'; end if;
  select * into again from public.finish_world_five_hidden(sid,array[]::integer[],500,300000,true);
  if receipt.game_score_id<>again.game_score_id or receipt.balance<>again.balance then raise exception 'same session paid twice'; end if;
  before_balance:=receipt.balance;
  sid:=public.begin_world_five_hidden(other_c,'king');
  update public.world_five_hidden_runs set started_at=now()-interval '5 minutes' where id=sid;
  select * into receipt from public.finish_world_five_hidden(sid,array[]::integer[],999,300000,true);
  if receipt.coins_earned<>0 or receipt.pet_granted or receipt.balance<>before_balance then raise exception 'cross-character duplicate reward'; end if;
  sid:=public.begin_world_five_hidden(c,'fever');
  begin perform public.begin_world_five_hidden(other_c,'fever');raise exception 'fever can reenter';
  exception when others then if sqlerrm<>'hidden stage already entered' then raise;end if;end;
  perform set_config('request.jwt.claim.sub',gen_random_uuid()::text,true);
  begin perform public.begin_world_five_hidden(c,'king');raise exception 'wrong owner entered';
  exception when others then if sqlerrm<>'character not found' then raise;end if;end;
  perform set_config('request.jwt.claim.sub','',true);
  insert into public.game_characters(player,name,class) values('hidtest','guest','warrior') returning id into c;
  insert into public.world_five_hidden_unlocks(character_id) values(c);
  insert into public.world_five_hidden_runs(character_id,kind,abandoned) values(c,'king',true);
  sid:=public.begin_world_five_hidden(c,'king');
  update public.world_five_hidden_runs set started_at=now()-interval '5 minutes' where id=sid;
  select * into receipt from public.finish_world_five_hidden(sid,array[]::integer[],499,300000,true);
  if receipt.coins_earned<>748 or receipt.pet_granted then raise exception 'guest first clear incorrect';end if;
  sid:=public.begin_world_five_hidden(c,'king');
  update public.world_five_hidden_runs set started_at=now()-interval '5 minutes' where id=sid;
  select * into receipt from public.finish_world_five_hidden(sid,array[]::integer[],999,300000,true);
  if receipt.coins_earned<>0 or receipt.pet_granted then raise exception 'guest replay rewarded';end if;
end $test$;
rollback;
